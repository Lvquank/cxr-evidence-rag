#!/usr/bin/env python3
"""Sweep global/local fusion weights from a saved retrieval similarity cache.

This utility deliberately does not load RAD-DINO or DenseNet.  It is valid only
for the candidate pool contained in the cache generated by
``evaluate_hybrid_cxr_retrieval.py --similarity-cache-json``.  A candidate with
no local score retains its global score; this preserves the original pipeline's
fallback when an image could not be read.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
from statistics import mean
from typing import Any, Iterable

import numpy as np


def dcg(values: Iterable[float]) -> float:
    values = list(values)
    return float(sum(value / math.log2(index + 2) for index, value in enumerate(values)))


def finite_mean(values: Iterable[float | None]) -> float | None:
    valid = [float(value) for value in values if value is not None and math.isfinite(float(value))]
    return float(mean(valid)) if valid else None


def metrics_for_query(query: dict[str, Any], global_weight: float, ks: list[int], threshold: float) -> dict[str, Any]:
    ranked = []
    for candidate in query["candidates"]:
        global_score = float(candidate["global_similarity"])
        local = candidate.get("local_similarity")
        local_score = global_score if local is None else float(local)
        score = global_weight * global_score + (1.0 - global_weight) * local_score
        ranked.append((score, int(candidate["global_rank"]), float(candidate["relevance"])))
    ranked.sort(key=lambda item: (-item[0], item[1]))
    total_relevant = int(query["total_relevant_in_gallery"])
    result: dict[str, Any] = {
        "query_id": query["query_id"],
        "query_study_id": query["query_study_id"],
        "candidate_pool_size": len(ranked),
        "total_relevant_in_gallery": total_relevant,
    }
    for k in ks:
        top = ranked[:k]
        relevance = np.asarray([item[2] for item in top], dtype=np.float64)
        binary = relevance >= threshold
        result[f"P@{k}"] = float(binary.mean()) if len(binary) else None
        if total_relevant and len(binary):
            hits = np.cumsum(binary)
            result[f"AP@{k}"] = float((hits / np.arange(1, len(binary) + 1) * binary).sum() / min(total_relevant, k))
        else:
            result[f"AP@{k}"] = None
        ideal = float(query.get("ideal_dcg", {}).get(str(k), 0.0))
        result[f"nDCG@{k}"] = dcg(relevance) / ideal if ideal else None
        supported = [item[0] for item in top if item[2] >= threshold]
        unsupported = [item[0] for item in top if item[2] == 0.0]
        result[f"Delta_path@{k}"] = (
            float(mean(supported) - mean(unsupported)) if supported and unsupported else None
        )
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description="Re-rank a saved retrieval candidate pool for a lambda sensitivity sweep.")
    parser.add_argument("--cache-json", required=True, type=Path)
    parser.add_argument("--output-json", required=True, type=Path)
    parser.add_argument("--output-csv", required=True, type=Path, help="Per-query metrics for every lambda.")
    parser.add_argument("--lambda-values", nargs="+", type=float, default=[1.0, 0.9, 0.7, 0.5, 0.3])
    parser.add_argument("--k", nargs="+", type=int, default=[5])
    parser.add_argument("--relevance-threshold", type=float, default=0.5)
    parser.add_argument("--freeze-lambda-global", type=float, help="Optional pre-specified lambda_global to record in --freeze-config-json.")
    parser.add_argument("--freeze-config-json", type=Path)
    args = parser.parse_args()

    if not args.lambda_values or any(not 0.0 <= value <= 1.0 for value in args.lambda_values):
        parser.error("--lambda-values must be within [0, 1].")
    if not args.k or any(value < 1 for value in args.k):
        parser.error("--k must contain positive values.")
    if not 0.0 < args.relevance_threshold <= 1.0:
        parser.error("--relevance-threshold must be in (0, 1].")
    if (args.freeze_lambda_global is None) != (args.freeze_config_json is None):
        parser.error("Use --freeze-lambda-global and --freeze-config-json together.")

    cache = json.loads(args.cache_json.read_text(encoding="utf-8"))
    queries = list(cache.get("queries", []))
    if not queries:
        raise ValueError("The cache contains no queries.")
    minimum_pool = min(len(query.get("candidates", [])) for query in queries)
    if max(args.k) > minimum_pool:
        raise ValueError(f"Largest K ({max(args.k)}) exceeds the smallest cached pool ({minimum_pool}).")

    per_query_rows: list[dict[str, Any]] = []
    summary_rows: list[dict[str, Any]] = []
    for global_weight in args.lambda_values:
        records = [metrics_for_query(query, global_weight, args.k, args.relevance_threshold) for query in queries]
        for record in records:
            record["lambda_global"] = global_weight
        per_query_rows.extend(records)
        row: dict[str, Any] = {"lambda_global": global_weight, "evaluated_queries": len(records)}
        for k in args.k:
            for name in (f"P@{k}", f"AP@{k}", f"nDCG@{k}", f"Delta_path@{k}"):
                row[name] = finite_mean(record[name] for record in records)
        summary_rows.append(row)

    args.output_json.parent.mkdir(parents=True, exist_ok=True)
    args.output_csv.parent.mkdir(parents=True, exist_ok=True)
    output = {
        "schema_version": 1,
        "protocol": {
            "score": "lambda_global * S_global + (1 - lambda_global) * S_local; missing S_local falls back to S_global",
            "candidate_universe": "cached global top-N unique studies only; do not describe this as a full-gallery reranking result",
            "same_study_removal": cache.get("protocol", {}).get("same_study_excluded"),
            "deduplication": cache.get("protocol", {}).get("deduplicate_by"),
            "relevance": cache.get("protocol", {}).get("relevance"),
            "relevance_threshold": args.relevance_threshold,
            "k": args.k,
            "cache_candidates": cache.get("protocol", {}).get("cache_candidates"),
            "source_runtime_lambda_global": cache.get("protocol", {}).get("lambda_global"),
        },
        "summary": summary_rows,
        "caveat": "Select a frozen lambda from a validation protocol, not by optimizing end-to-end test outcomes.",
    }
    args.output_json.write_text(json.dumps(output, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    fieldnames = list(per_query_rows[0])
    with args.output_csv.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(per_query_rows)

    if args.freeze_config_json:
        args.freeze_config_json.parent.mkdir(parents=True, exist_ok=True)
        args.freeze_config_json.write_text(json.dumps({
            "lambda_global": args.freeze_lambda_global,
            "lambda_local": 1.0 - args.freeze_lambda_global,
            "score": "lambda_global * S_global + (1 - lambda_global) * S_local",
            "selected_before_end_to_end_test": True,
            "source_cache": str(args.cache_json.resolve()),
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(json.dumps({"output_json": str(args.output_json), "output_csv": str(args.output_csv), "summary": summary_rows}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
